// Görevin başlığı/açıklaması (bölge yoksa Zonguldak)
export function gorevYazi(bolge, i) {
  const l = GOREV_YAZI[bolge] || GOREV_YAZI.zonguldak
  return l[i] || null
}

// Görev i (0 tabanlı) alındıktan sonra oynayacak sahne kimliği ya da null
export function gorevSahnesi(bolge, i) {
  const y = gorevYazi(bolge, i)
  const id = bolge + '-' + (i + 1)
  return y && y.sahne && SAHNELER[id] ? id : null
}

// Sahnenin ait olduğu bölüm (hikâye defteri için)
export function sahneBolumu(id) {
  if (id === 'giris' || id === 'ogretici' || id === 'kaya' || id === 'kesif') return 'zonguldak'
  if (id.startsWith('prestij')) return 'prestij'
  return id.split('-')[0]
}
